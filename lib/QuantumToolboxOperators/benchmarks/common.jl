# ─── Configuration ───────────────────────────────────────────────────────────

const SIZE = get(ENV, "QTO_BENCH_SIZE", "full")
SIZE in ("smoke", "full") || error("QTO_BENCH_SIZE must be \"smoke\" or \"full\", got \"$SIZE\"")

const WANT_REACTANT = get(ENV, "QTO_BENCH_REACTANT", "0") == "1"
const SECONDS = SIZE == "smoke" ? 0.1 : 0.5

# ─── Backends ────────────────────────────────────────────────────────────────

"""
    Backend(name, available, to_device, to_sparse, wrap)

A place to run a benchmark.

`wrap` is the important field: it takes a closure and returns a closure that also *waits* for the
work to finish. CUDA kernel launches are asynchronous, so timing an unwrapped `mul!` on device
arrays measures launch latency, not throughput — which is precisely how the original workshop
notebook ended up reporting that a 10-kernel lazy Hamiltonian was "slower" than a 1-kernel sparse
one. Every device measurement must go through `wrap`.
"""
struct Backend
    name::String
    available::Bool
    to_device::Function
    to_sparse::Function
    wrap::Function
end

const CPU_BACKEND = Backend("CPU", true, identity, identity, f -> f)

function cuda_backend()
    CUDA.functional() || return Backend("CUDA", false, identity, identity, f -> f)
    return Backend(
        "CUDA", true,
        x -> CUDA.CuArray(x),
        A -> CUDA.CUSPARSE.CuSparseMatrixCSR(A),
        f -> (() -> CUDA.@sync f()),
    )
end

# ─── Measurement ─────────────────────────────────────────────────────────────

"""
    measure(f, backend) -> (min, median) in seconds, or `nothing`

Warm up, then benchmark. Returns `nothing` if the closure throws, so one broken cell cannot take
down a long run.
"""
function measure(f, backend::Backend)
    g = backend.wrap(f)
    try
        g()  # warm up / compile
        b = @be g seconds = SECONDS
        return (min = minimum(x -> x.time, b.samples), median = median(map(x -> x.time, b.samples)))
    catch err
        @warn "benchmark failed on $(backend.name)" exception = (err, catch_backtrace())
        return nothing
    end
end

# ─── Results ─────────────────────────────────────────────────────────────────

"""
A single measured row. `status` is `"PASS"`/`"FAIL"` from an equality check against a reference,
so a fast-but-wrong number can never be published silently.
"""
Base.@kwdef struct Result
    group::String
    case::String
    backend::String
    variant::String                   # "lazy", "sparse", "TensorProductOperator", …
    time_min::Union{Float64, Nothing} = nothing
    time_median::Union{Float64, Nothing} = nothing
    compile_s::Union{Float64, Nothing} = nothing
    bytes_op::Union{Int, Nothing} = nothing
    bytes_cached::Union{Int, Nothing} = nothing
    status::String = "n/a"
end

const RESULTS = Result[]

record!(r::Result) = (push!(RESULTS, r); r)

"""
    check(actual, expected) -> "PASS" | "FAIL"

Loose tolerance: these run in ComplexF32 at large N, where a different summation order across
backends legitimately moves the last few bits.
"""
function check(actual, expected)
    a, e = Array(actual), Array(expected)
    return isapprox(a, e; rtol = 1.0f-3, atol = 1.0f-4) ? "PASS" : "FAIL"
end

# ─── Formatting ──────────────────────────────────────────────────────────────

"""
    _short_reason(err) -> String

First line of an exception message, trimmed — enough to say *why* a cell is `n/a` in the results
table without pasting a Reactant stack trace into markdown.
"""
function _short_reason(err)
    msg = first(split(sprint(showerror, err), '\n'))
    msg = replace(msg, '|' => '/')            # markdown table safety
    return length(msg) > 70 ? first(msg, 67) * "…" : msg
end

fmt_time(::Nothing) = "n/a"
fmt_time(t::Float64) = t < 1.0e-3 ? @sprintf("%.2f µs", t * 1.0e6) : @sprintf("%.2f ms", t * 1.0e3)

fmt_bytes(::Nothing) = "n/a"
function fmt_bytes(b::Int)
    b < 1024 && return "$b B"
    b < 1024^2 && return @sprintf("%.1f KiB", b / 1024)
    b < 1024^3 && return @sprintf("%.1f MiB", b / 1024^2)
    return @sprintf("%.2f GiB", b / 1024^3)
end

fmt_ratio(::Nothing, _) = "n/a"
fmt_ratio(_, ::Nothing) = "n/a"
fmt_ratio(a::Real, b::Real) = iszero(b) ? "n/a" : @sprintf("%.2f×", a / b)

function provenance_header(io)
    println(io, "# QuantumToolboxOperators — benchmark results")
    println(io)
    println(io, "Generated by `benchmarks/runbenchmarks.jl`. Do not edit by hand.")
    println(io)
    println(io, "| | |")
    println(io, "|---|---|")
    println(io, "| Date | $(Dates.format(now(), "yyyy-mm-dd HH:MM")) |")
    println(io, "| Julia | $(VERSION) |")
    println(io, "| CPU | $(Sys.CPU_NAME), $(Sys.CPU_THREADS) threads |")
    println(io, "| Julia threads | $(Threads.nthreads()) |")
    println(io, "| BLAS threads | $(BLAS.get_num_threads()) |")
    if CUDA.functional()
        println(io, "| GPU | $(CUDA.name(CUDA.device())) |")
        println(io, "| CUDA runtime | $(CUDA.runtime_version()) |")
    else
        println(io, "| GPU | not available |")
    end
    println(io, "| Reactant / XLA | $(REACTANT_STATUS[]) |")
    println(io, "| `QTO_BENCH_SIZE` | `$SIZE` |")
    for (name, ver) in sort(collect(PKG_VERSIONS[]))
        println(io, "| $name | $ver |")
    end
    println(io)
    return println(
        io, """
        !!! note "How these numbers are taken"
            Times are the **minimum** over Chairmarks samples. Every GPU measurement is wrapped in
            `CUDA.@sync`, so it reflects completed work rather than kernel-launch latency — the
            figures in the original workshop notebook were *not* synchronized and are therefore not
            comparable with these. `Base.summarysize` on a device-backed operator counts the
            host-side wrapper only, not device memory. XLA compile time is reported in its own
            column and is never folded into the steady-state time.
        """
    )
end

const REACTANT_STATUS = Ref("not requested")
const PKG_VERSIONS = Ref(Dict{String, String}())

function collect_pkg_versions()
    d = Dict{String, String}()
    for (_, dep) in Pkg.dependencies()
        dep.name in ("SciMLOperators", "CUDA", "Reactant", "QuantumToolbox") || continue
        d[dep.name] = string(dep.version)
    end
    return d
end

"""
    emit_table(io, rows; columns)

Render `rows` as a markdown table. `columns` is a vector of `name => row -> cell` pairs.
"""
function emit_table(io, rows; columns)
    isempty(rows) && return println(io, "_no results_\n")
    println(io, "| ", join(first.(columns), " | "), " |")
    println(io, "|", join(fill("---", length(columns)), "|"), "|")
    for r in rows
        println(io, "| ", join((c.second(r) for c in columns), " | "), " |")
    end
    return println(io)
end

